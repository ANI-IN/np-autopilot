#!/usr/bin/env python3
"""Generate docs/ACCEPTANCE-CHECKLIST.md — every module's links, to click.

GENERATED, not hand-written, for the reason every count in this project is:
a hand-maintained list of 20 modules x 8 items goes stale on the next crawl and
nobody notices until someone clicks a dead link. `tests/test_source_links.py`
asserts the properties; this file is what a human actually checks.
"""
from __future__ import annotations

import collections
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pipeline.lib import graphio, taxonomy as tax                     # noqa: E402
from pipeline.lib.paths import REPO_ROOT                              # noqa: E402

OUT = REPO_ROOT / "docs" / "ACCEPTANCE-CHECKLIST.md"

KIND_ORDER = ["pre_class", "class", "alternate_class", "task", "review",
              "alternate_review", "post_class"]
KIND_LABEL = {"pre_class": "Pre-class", "class": "Class",
              "alternate_class": "Alternate Class", "task": "Assignment",
              "review": "Assignment Review", "alternate_review": "Alt. Review",
              "post_class": "Practice problems"}
DOMAIN = {"full-stack": "SD1", "frontend": "SD2", "backend": "SD3",
          "testing": "SD4"}


def main() -> int:
    g = graphio.load_merged(include_sensitive=False)
    N = {n["id"]: n for n in g["nodes"]}
    OUTE = collections.defaultdict(list)
    INE = collections.defaultdict(list)
    for e in g["edges"]:
        OUTE[e["source"]].append(e)
        INE[e["target"]].append(e)
    R = {r: tax.edge_for_role(r) for r in ("module_session", "domain_module")}

    mods = sorted((n for n in g["nodes"]
                   if n["type"] == "module" and n.get("domain_slug")),
                  key=lambda m: (m["domain_slug"], m.get("sequence") or 0))

    lines = [
        "# ACCEPTANCE CHECKLIST — source links",
        "",
        "**Generated by `pipeline/gen_acceptance_checklist.py`. Do not edit.**",
        "",
        "Every item shows all of its direct links. The mastersheet is never an",
        "item's link — it is the citation and appears under Provenance.",
        "",
        "Everyone at IK has view access to these Drive folders and to Uplevel",
        "(`config/out-of-corpus-facts.yaml`), so no access caveat is shown. A",
        "download-disabled file still gets its Drive link: `canDownload: false`",
        "stops an export, not a person opening it.",
        "",
        "Where a link is absent the reason is stated rather than guessed, and",
        "nothing ever falls back to the spreadsheet.",
        "",
    ]

    tot = ok = 0
    for m in mods:
        dom = next((N[e["source"]] for e in INE[m["id"]]
                    if e["rel"] == R["domain_module"]), None)
        tag = f"{DOMAIN.get(m['domain_slug'], m['domain_slug'])}/{m.get('sequence')}"
        lines.append(f"## {tag} · {m['label']}")
        lines.append("")
        lines.append("| item | Uplevel | Drive |")
        lines.append("|---|---|---|")

        up = m.get("uplevel_link") or ""
        folder = (dom or {}).get("drive_folder_url") or ""
        tot += 1
        ok += bool(up)
        lines.append(
            f"| **Module** | {f'[open]({up})' if up else '_no Uplevel link_'} "
            f"| {f'[{dom[chr(39)+chr(39)] if False else dom['label']} folder]({folder})' if folder else '_no Drive folder: pass 6 records file ids, not folder ids_'} |")

        sessions, attached = {}, collections.defaultdict(list)
        for e in OUTE[m["id"]]:
            if e["rel"] != R["module_session"]:
                continue
            n = N[e["target"]]
            if e.get("attached_file"):
                attached[e.get("session_kind") or ""].append(
                    (e["attached_file"], e.get("attached_drive_url") or ""))
            else:
                sessions[n.get("session_kind") or "?"] = n

        for k in KIND_ORDER:
            n = sessions.get(k)
            if not n:
                why = ("not offered — optional per module" if k == "post_class"
                       else "not in the mastersheet for this module")
                lines.append(f"| {KIND_LABEL[k]} | _{why}_ | — |")
                continue
            tot += 1
            u = n.get("uplevel_link") or ""
            ok += bool(u)
            # EVERY FILE, BY ITS FULL NAME. This listed the first 3, each cut to
            # 34 characters, with no count: API Design's Class row showed 3 of
            # its 13 decks, and the owner ticks every link against the
            # mastersheet. A cap that drops links silently is CLAUDE.md §4's
            # filter on truth, and a truncated filename is a broken citation
            # key (§1). tests/test_acceptance_checklist.py holds it to the graph.
            files = sorted(attached.get(k, []))
            drive = (f"**{len(files)}:** " + ", ".join(
                f"[{nm.replace('|', '/')}]({url})" if url else nm.replace('|', '/')
                for nm, url in files)) \
                if files else "_no file matched at session level_"
            lines.append(f"| {KIND_LABEL[k]} | "
                         f"{f'[open]({u})' if u else '_no Uplevel link_'} | {drive} |")
        lines.append("")

    lines.insert(len(lines) and 12,
                 f"**{ok} of {tot} linkable items carry an Uplevel link.** "
                 f"The rest state a reason.\n")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  -> {OUT.relative_to(REPO_ROOT)}  ({len(mods)} modules, "
          f"{ok}/{tot} items linked)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
